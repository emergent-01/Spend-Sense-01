import dayjs from "dayjs";
import type { Tx } from "@/src/api";
import { inr } from "@/src/format";

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

// Printable claim report: summary table + original bank SMS for each item as proof.
export function claimReportHtml(txs: Tx[], periodLabel: string, name: string | null, email: string | undefined): string {
  const total = txs.reduce((s, t) => s + t.amount, 0);
  const rows = txs
    .map(
      (t, i) => `<tr><td>${i + 1}</td><td>${dayjs(t.ts).format("DD MMM YYYY")}</td><td>${esc(t.merchant)}</td><td>${esc(t.category)}${t.business ? " · Business" : ""}</td><td class="r">${inr(t.amount, true)}</td></tr>`,
    )
    .join("");
  const proofs = txs
    .map(
      (t, i) => `<div class="proof"><div class="ph"><b>#${i + 1} · ${esc(t.merchant)}</b><span>${dayjs(t.ts).format("DD MMM YYYY, h:mm A")} · ${inr(t.amount, true)}</span></div>
      ${
        t.raw.length
          ? t.raw.map((r) => `<pre>${esc(r)}</pre>`).join("")
          : `<pre class="none">Added manually${t.note ? ` — ${esc(t.note)}` : ""} (no bank SMS)</pre>`
      }
      ${[t.bank, t.card_last4 ? `Card ••${t.card_last4}` : null, t.vpa ? `UPI ${esc(t.vpa)}` : null].filter(Boolean).length ? `<div class="meta">${[t.bank, t.card_last4 ? `Card ••${t.card_last4}` : null, t.vpa ? `UPI ${esc(t.vpa)}` : null].filter(Boolean).join(" · ")}</div>` : ""}
      </div>`,
    )
    .join("");
  return `<!doctype html><html><head><meta charset="utf-8"/><title>Claim report ${esc(periodLabel)}</title>
<style>
  * { box-sizing: border-box; }
  body { font-family: -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; color: #1C1F1D; margin: 32px; font-size: 12px; }
  h1 { font-size: 22px; margin: 0 0 4px; color: #2F4F3A; }
  .sub { color: #6D736F; margin-bottom: 20px; }
  .tot { display: flex; justify-content: space-between; background: #E7EFE8; border-radius: 10px; padding: 14px 16px; margin-bottom: 18px; }
  .tot b { font-size: 18px; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
  th { text-align: left; font-size: 11px; color: #6D736F; border-bottom: 1.5px solid #C9D8CB; padding: 8px 6px; }
  td { padding: 8px 6px; border-bottom: 1px solid #EAECE5; vertical-align: top; }
  .r { text-align: right; white-space: nowrap; }
  tfoot td { font-weight: 700; border-top: 1.5px solid #C9D8CB; }
  h2 { font-size: 15px; margin: 24px 0 10px; color: #2F4F3A; }
  .proof { border: 1px solid #EAECE5; border-radius: 10px; padding: 10px 12px; margin-bottom: 10px; page-break-inside: avoid; }
  .ph { display: flex; justify-content: space-between; margin-bottom: 6px; gap: 12px; }
  .ph span { color: #6D736F; }
  pre { white-space: pre-wrap; word-break: break-word; font-family: Menlo, Consolas, monospace; font-size: 11px; background: #F4F5F0; padding: 8px; border-radius: 6px; margin: 4px 0; }
  pre.none { color: #6D736F; }
  .meta { color: #6D736F; font-size: 10px; }
  .foot { color: #6D736F; font-size: 10px; margin-top: 24px; }
</style></head><body>
<h1>Expense claim report</h1>
<div class="sub">${esc(periodLabel)} · ${esc(name || "")}${email ? ` (${esc(email)})` : ""} · generated ${dayjs().format("DD MMM YYYY")}</div>
<div class="tot"><span>${txs.length} claimable transaction${txs.length === 1 ? "" : "s"}</span><b>${inr(total, true)}</b></div>
<table><thead><tr><th>#</th><th>Date</th><th>Merchant</th><th>Category</th><th class="r">Amount</th></tr></thead>
<tbody>${rows}</tbody><tfoot><tr><td colspan="4">Total</td><td class="r">${inr(total, true)}</td></tr></tfoot></table>
<h2>Proof — original bank SMS</h2>
${proofs}
<div class="foot">Generated by SpendSense from bank transaction alerts received on the claimant's phone.</div>
</body></html>`;
}
